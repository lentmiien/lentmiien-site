// DEVELOPMENT ONLY. Generate a pasteable pure diagnostic from the exact
// production predicates, without importing any application module.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const between = (source, start, end) => {
  const from = source.indexOf(start); const to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`Missing diagnostic source boundary: ${start}`);
  return source.slice(from, to);
};
function build() {
  const locality = read('utils/disasterLocality.js');
  const evidence = read('utils/disasterLocalEvidence.js');
  const summary = read('services/disasterLocalSummaryService.js');
  const parserVersion = read('utils/disasterJmaParser.js').match(/const PARSER_VERSION = ('[^']+');/)[1];
  const modules = {
    './disasterJmaMunicipality': read('utils/disasterJmaMunicipality.js'),
    './disasterLocality': between(locality, 'const LOCALITY =', 'function locationConfig') +
      between(locality, 'function localWarningCode', 'function distanceKm') + 'module.exports = { LOCALITY, localWarningCode };',
    './disasterLocalEvidence': "const { LOCALITY, localWarningCode } = require('./disasterLocality');\n" +
      "const { municipalityWarnings, completeMunicipalityWarnings, municipalKind } = require('./disasterJmaMunicipality');\n" +
      between(evidence, 'const array =', 'const INTENSITIES =') +
      between(evidence, 'function productOf', 'function earthquakeEvidence') +
      'module.exports = { date, productOf, warningEvidence };',
    './disasterJmaParser': `module.exports = { PARSER_VERSION: ${parserVersion} };`,
    './disasterJmaReadiness': read('utils/disasterJmaReadiness.js'),
    './summaryOrdering': "const { date } = require('./disasterLocalEvidence');\n" +
      between(summary, 'const millis =', 'const stamp =') + 'module.exports = { order, freshness };',
  };
  return '// GENERATED by scripts/build-jma-warning-diagnostic.js; do not edit.\n' +
    '// Paste this entire expression into an isolated JS context; it returns a function.\n' +
    '// No external require, DB, provider, filesystem, environment, timers or logging.\n' +
    '(() => {\nconst modules = Object.create(null);\n' +
    Object.entries(modules).map(([name, code]) => `modules[${JSON.stringify(name)}] = (() => {\nconst module = { exports: {} };\nconst require = id => { if (!Object.hasOwn(modules, id)) throw new Error('External dependency forbidden'); return modules[id]; };\n${code}\nreturn module.exports;\n})();\n`).join('') +
    read('scripts/jma-warning-diagnostic-body.js') + '\n})()\n';
}
if (require.main === module) fs.writeFileSync(path.join(root, 'documentation/diagnostics/jma-warning-v3.js'), build());
module.exports = { build };
